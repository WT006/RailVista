const BY_PROV = new Map<string, PrefectureSeed[]>();
for (const [p, n, lng, lat] of RAW) {
  const row: PrefectureSeed = { p, n, lng, lat };
  const list = BY_PROV.get(p);
  if (list) list.push(row);
  else BY_PROV.set(p, [row]);
}

const WIDE = new Set(['新疆', '西藏', '内蒙古', '青海', '甘肃', '黑龙江']);

function pointInFlatRing(lng: number, lat: number, flat: number[]): boolean {
  let inside = false;
  const n = (flat.length / 2) | 0;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    const xi = flat[i * 2]! / 1e4;
    const yi = flat[i * 2 + 1]! / 1e4;
    const xj = flat[j * 2]! / 1e4;
    const yj = flat[j * 2 + 1]! / 1e4;
    const denom = yj - yi || 1e-12;
    const inter = yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / denom + xi;
    if (inter) inside = !inside;
  }
  return inside;
}

function pipPlace(lng: number, lat: number): AtlasPlace | null {
  let best: PrefUnit | null = null;
  let bestA = Infinity;
  for (const u of UNITS) {
    const [minLng, minLat, maxLng, maxLat] = u.b;
    if (lng < minLng || lng > maxLng || lat < minLat || lat > maxLat) continue;
    let hit = false;
    for (const poly of u.g) {
      const outer = poly[0];
      if (!outer || !pointInFlatRing(lng, lat, outer)) continue;
      let inHole = false;
      for (let i = 1; i < poly.length; i++) {
        const hole = poly[i];
        if (hole && pointInFlatRing(lng, lat, hole)) {
          inHole = true;
          break;
        }
      }
      if (!inHole) {
        hit = true;
        break;
      }
    }
    if (hit && u.a < bestA) {
      bestA = u.a;
      best = u;
    }
  }
  if (!best) return null;
  if (best.p === '台湾' && best.n === '台湾') {
    const tw = nearestSeedInProv(lng, lat, '台湾');
    if (tw) return { province: '台湾', city: tw.n };
  }
  return { province: best.p, city: best.n };
}

function nearestSeedInProv(lng: number, lat: number, prov: string): PrefectureSeed | null {
  const seeds = BY_PROV.get(prov);
  if (!seeds?.length) return null;
  let best: PrefectureSeed | null = null;
  let bestD = Infinity;
  for (const s of seeds) {
    const d = (s.lng - lng) ** 2 + (s.lat - lat) ** 2;
    if (d < bestD) {
      bestD = d;
      best = s;
    }
  }
  return best;
}

function nearestSeed(lng: number, lat: number): PrefectureSeed | null {
  let best: PrefectureSeed | null = null;
  let bestD = Infinity;
  for (const list of BY_PROV.values()) {
    for (const s of list) {
      const d = (s.lng - lng) ** 2 + (s.lat - lat) ** 2;
      if (d < bestD) {
        bestD = d;
        best = s;
      }
    }
  }
  if (!best) return null;
  const maxDeg = WIDE.has(best.p) ? 6 : 2.8;
  if (bestD > maxDeg * maxDeg) return null;
  return best;
}

const PLACE_CACHE = new Map<string, AtlasPlace>();

/** 图集归市：真实政区界优先（含港/澳），未命中再全国最近驻地。 */
export function placeOfPoint(lng: number, lat: number, storedProvince?: string): AtlasPlace {
  const key = `${Math.round(lng * 1e5)}_${Math.round(lat * 1e5)}`;
  const cached = PLACE_CACHE.get(key);
  if (cached) return cached;
  const pip = pipPlace(lng, lat);
  const seed = pip ? null : nearestSeed(lng, lat);
  const place: AtlasPlace = pip
    ? pip
    : seed
      ? { province: seed.p, city: seed.n }
      : { province: String(storedProvince ?? '').trim() || '未分市', city: String(storedProvince ?? '').trim() || '未分市' };
  PLACE_CACHE.set(key, place);
  return place;
}

export function cityOfPoint(lng: number, lat: number, province?: string): string {
  return placeOfPoint(lng, lat, province).city;
}

/**
 * 公路景点展示归属：按经纬度重算，不把库内 province 当权威。
 * 命中地级界 → 界内省/市；未命中再退回采集标签（不用最近驻地，避免港/澳并进广东）。
 */
export function roadDisplayPlace(
  lng: number,
  lat: number,
  storedProvince?: string,
): { displayProvince: string; displayCity: string } {
  const pip = pipPlace(lng, lat);
  if (pip) {
    const displayProvince = pip.province.trim() || '未标注省份';
    const displayCity = pip.city.trim() || displayProvince;
    return { displayProvince, displayCity };
  }
  const stored = String(storedProvince ?? '').trim();
  const displayProvince = stored || '未标注省份';
  return { displayProvince, displayCity: displayProvince };
}
