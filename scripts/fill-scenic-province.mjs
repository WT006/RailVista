function bboxHits(lng, lat) {
  return PROVINCE_BBOXES.filter(
    (p) => lat >= p.bbox[0] && lng >= p.bbox[1] && lat <= p.bbox[2] && lng <= p.bbox[3],
  ).map((p) => p.name);
}

const main = JSON.parse(readFileSync(target, 'utf8'));
const unresolved = [];
let filled = 0;
for (const s of main.spots) {
  if (s.province) continue;
  const hits = bboxHits(s.lng, s.lat);
  let prov = null;

  // L1 tags 省名
  for (const t of (s.tags || [])) {
    if (PROV_NAMES.has(t)) { prov = t; break; }
  }

  // L2 bbox 恰 1 省
  if (!prov && hits.length === 1) prov = hits[0];

  // L3 走廊归属消歧
  if (!prov) {
    const corridors = (s.lines || []).map((l) => l.corridorId);
    if (corridors.length) {
      const provs = new Set(corridors.flatMap((c) => CORRIDOR_PROV[c] || []));
      const inter = hits.filter((h) => provs.has(h));
      if (inter.length === 1) prov = inter[0];
    }
  }

  // L4 市县地名关键词消歧（与 bbox 命中集求交，多省命中且无法消歧则不猜测）
  if (!prov) {
    const text = String(s.name || '') + (s.tags || []).join('');
    const provs = new Set();
    for (const [kw, p] of Object.entries(CITY_PROV)) {
      if (text.includes(kw)) provs.add(p);
    }
    if (provs.size) {
      const inter = hits.filter((h) => provs.has(h));
      if (inter.length === 1) prov = inter[0];
      else if (inter.length === 0 && provs.size === 1 && hits.length === 0) prov = [...provs][0];
    }
  }

  if (prov) {
    s.province = prov;
    s.reviewedAt = reviewedAt;
    filled += 1;
  } else {
    unresolved.push(s);
  }
}

